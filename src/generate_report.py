"""Generate the one-page portfolio risk report from the OFE tracker data.

Usage:
    python3 src/generate_report.py
Reads  data/ofe_line_items.csv
Writes reports/portfolio_risk_report.md and prints the KPI summary as JSON.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ofe_kpi import compute_all, load_items  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "ofe_line_items.csv"
OUT = ROOT / "reports" / "portfolio_risk_report.md"


def _pct(rate: float | None) -> str:
    return "n/a" if rate is None else f"{rate:.1%}"


def _drift_table(title: str, groups: dict) -> list[str]:
    lines = [f"### Drift by {title}", "",
             "| Group | Items | Mean drift (d) | Max drift (d) | Late items |",
             "|---|---|---|---|---|"]
    for name, g in groups.items():
        lines.append(
            f"| {name} | {g['count']} | {g['mean_drift_days']:+.1f} | "
            f"{g['max_drift_days']:+d} | {g['late_items']} |")
    lines.append("")
    return lines


def render(k: dict) -> str:
    otr = k["on_time_to_ros"]
    fot = k["forecast_on_time"]
    esc = k["escalation_cycle_time"]
    risk = k["risk_summary"]
    lines = [
        "# OFE Portfolio Risk Report (one page)",
        "",
        "> **SIMULATED DATA - not a real project.** All sites, line items, dates "
        "and suppliers in this report are fictional, generated to demonstrate the "
        "portfolio risk view used in a Capacity Delivery Review. No real employer, "
        "customer, or order data is included.",
        "",
        "## Portfolio at a glance",
        "",
        f"- Line items tracked: **{k['total_items']}** across 2 simulated sites",
        f"- On-time-to-ROS (delivered items): **{otr['on_time']}/{otr['delivered']} "
        f"= {_pct(otr['rate'])}**",
        f"- Forecast on-time (all items, forecast vs plan): "
        f"**{fot['on_time_forecast']}/{fot['total']} = {_pct(fot['rate'])}**",
        f"- Risk mix: " + ", ".join(
            f"{r} {n}" for r, n in sorted(risk["by_rating"].items())),
        f"- Open high-risk items: **{', '.join(risk['open_high_risk']) or 'none'}**",
        f"- Escalations closed: {esc['closed_count']} "
        f"(mean cycle {esc['mean_cycle_days']} d, max {esc['max_cycle_days']} d); "
        f"open: {', '.join(esc['open_items']) or 'none'}",
        "",
        "## Slip scenarios in this snapshot (the three risks that matter)",
        "",
        "| Item | Scenario | Site / Category | Supplier | Drift | Status |",
        "|---|---|---|---|---|---|",
    ]
    for s in k["slip_scenarios"]:
        lines.append(
            f"| {s['line_item_id']} | {s['scenario']} | {s['site']} / "
            f"{s['equipment_category']} | {s['supplier']} | {s['drift_days']:+d} d | "
            f"{s['escalation_status']} |")
    lines += ["", "What each slip needs (detail in docs/expediting_playbook.md):", ""]
    for s in k["slip_scenarios"]:
        lines.append(f"- **{s['line_item_id']} ({s['scenario']})** - {s['notes']}")
    lines.append("")
    lines += _drift_table("supplier", k["drift_by_supplier"])
    lines += _drift_table("category", k["drift_by_category"])
    lines += _drift_table("site", k["drift_by_site"])
    lines += [
        "## Reading this page in a Capacity Delivery Review",
        "",
        "1. Start from open high-risk items and the slip table - those are the only "
        "items that can still move a ready-for-service date.",
        "2. Drift by supplier/category is a pattern view, not a blame view: a "
        "supplier drifting across categories is a capacity signal; one category "
        "drifting across suppliers is a design or submittal signal.",
        "3. Every late item on this page carries a decision, not just a status: "
        "expedite, partial ship, resequence, or escalate - see the playbook.",
        "",
        "Generated by src/generate_report.py from data/ofe_line_items.csv "
        "(simulated). KPI definitions: src/ofe_kpi.py module docstring.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    items = load_items(DATA)
    kpis = compute_all(items)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(kpis), encoding="utf-8")
    print(json.dumps(kpis, indent=2, default=str))
    print(f"\nReport written to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
